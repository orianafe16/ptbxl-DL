"""Contribution tables of the DL reports, generated from docs/PLAN_DL.md.

Chat DL 10, 2026-11-24. The course asks each team member for an individual
report "clearly describing her/his specific activities" (Presentation III);
DECISIONS D9 says the contribution table is generated from the task log of
PLAN_DL.md, which records who actually did and who reviewed each task. Nothing
is typed by hand: run again after PLAN_DL.md changes.

    python common/make_contributions.py      (from report/)

Writes:
  common/contributions.tex      the whole task log (both authors)
  common/contributions_OF.tex   tasks in which OF took part, with her role
  common/contributions_MM.tex   the same for MM
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
PLAN = HERE.parent.parent / "docs" / "PLAN_DL.md"

AUTHORS = {"OF": "Oriana Ferraz (OF)", "MM": "Mar\\'ia Mart\\'inez (MM)"}


def tex(s: str) -> str:
    """Markdown cell -> LaTeX: `code` to \\texttt, escape special characters."""
    out = []
    for i, part in enumerate(s.split("`")):
        part = (part.replace("\\", "\\textbackslash{}").replace("&", "\\&")
                .replace("%", "\\%").replace("#", "\\#").replace("_", "\\_")
                .replace("$", "\\$").replace("—", "---").replace("–", "--"))
        out.append(f"\\texttt{{{part}}}" if i % 2 else part)
    return "".join(out)


def task_log(text: str) -> list[dict]:
    """Rows of the table under '## Task log'."""
    section = text.split("## Task log", 1)[1].split("\n## ", 1)[0]
    rows, header = [], None
    for line in section.splitlines():
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if set("".join(cells)) <= set("-: "):
            continue
        if header is None:
            header = cells
            continue
        rows.append(dict(zip(header, cells)))
    return rows


def role(row: dict, who: str) -> str | None:
    """Role of `who` (OF or MM) in a task, from the columns that record what
    happened ('Done by', 'Reviewed by'); for tasks not yet done, from the
    planned 'Owner' / 'Reviewer'."""
    done, rev = row["Done by"], row["Reviewed by"]
    if row["Status"] == "done":
        roles = []
        if who in done:
            roles.append("did (shared)" if "OF + MM" in done else "did")
        if who in rev:
            roles.append("reviewed")
        if "each" in row["Owner"]:
            roles = ["did her own part" + (", cross review" if "cross" in rev else "")]
        return ", ".join(roles) or None
    planned = []
    if who in row["Owner"] or "each" in row["Owner"]:
        planned.append("owner")
    if who in row["Reviewer"]:
        planned.append("reviewer")
    return ("planned: " + ", ".join(planned)) if planned else None


def full_table(rows: list[dict]) -> str:
    lines = ["% Generated by common/make_contributions.py from docs/PLAN_DL.md. Do not edit.",
             "{\\footnotesize",
             "\\begin{tabularx}{\\textwidth}{l>{\\raggedright\\arraybackslash}X"
             ">{\\raggedright\\arraybackslash}p{1.7cm}>{\\raggedright\\arraybackslash}p{3.3cm}"
             ">{\\raggedright\\arraybackslash}p{1.4cm}l}",
             "\\toprule",
             "ID & Task & Status & Done by & Reviewed by & Date \\\\",
             "\\midrule"]
    for r in rows:
        lines.append(" & ".join(tex(r[k]) for k in
                                ("ID", "Task", "Status", "Done by", "Reviewed by", "Date"))
                     + " \\\\")
    lines += ["\\bottomrule", "\\end{tabularx}}", ""]
    return "\n".join(lines)


def author_table(rows: list[dict], who: str) -> str:
    lines = [f"% Generated by common/make_contributions.py from docs/PLAN_DL.md ({who}). Do not edit.",
             "{\\small",
             "\\begin{tabularx}{\\textwidth}{l>{\\raggedright\\arraybackslash}X"
             ">{\\raggedright\\arraybackslash}p{3.6cm}l}",
             "\\toprule",
             f"ID & Task & Role of {AUTHORS[who].split(' (')[0]} & Status \\\\",
             "\\midrule"]
    for r in rows:
        ro = role(r, who)
        if ro:
            lines.append(f"{tex(r['ID'])} & {tex(r['Task'])} & {tex(ro)} & {tex(r['Status'])} \\\\")
    lines += ["\\bottomrule", "\\end{tabularx}}", ""]
    return "\n".join(lines)


def main() -> None:
    rows = task_log(PLAN.read_text(encoding="utf-8"))
    if not rows or not re.match(r"T\d+", rows[0]["ID"]):
        raise SystemExit("task log not found in PLAN_DL.md")
    (HERE / "contributions.tex").write_text(full_table(rows), encoding="utf-8")
    for who in AUTHORS:
        (HERE / f"contributions_{who}.tex").write_text(author_table(rows, who),
                                                       encoding="utf-8")
    print(f"{len(rows)} tasks from {PLAN}")


if __name__ == "__main__":
    main()

"""Generate report/numbers.tex from the JSON logs (DECISIONS D4, D14).

No number is typed by hand in the reports: they use macros such as
\\edaNRecordsAll{} that this script defines from results/logs/*.json.

    python report/make_numbers.py

Which logs are read: only those listed in report/runs.json, as
"alias": "log file name without .json", e.g.

    {"eda": "eda", "trivial": "trivial_e2e_s42_20261121-101500"}

Every key of the log's `scalars` block becomes the macro \\<alias><Key>.
The key is cut at underscores and at letter/digit boundaries; each letter
part starts with a capital letter and keeps the rest of its case; each
digit is spelled out:

    n_with_1_labels -> \\edaNWithOneLabels
    prev_train_MI   -> \\edaPrevTrainMI
    lead_std_V1     -> \\edaLeadStdVOne

Formats: integers with a thousands separator (21{,}799); other numbers
with 3 decimals; keys starting with frac_ or prev_ also give a percentage
macro ending in Pct, with 1 decimal. Write \\edaNRecordsAll{} (with the
braces) in the text so the following space is kept.
"""
import argparse
import json
import math
import re
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src import config  # noqa: E402

RUNS_FILE = config.REPORT_DIR / "runs.json"
OUT_FILE = config.REPORT_DIR / "numbers.tex"
DIGITS = ["Zero", "One", "Two", "Three", "Four",
          "Five", "Six", "Seven", "Eight", "Nine"]
PCT_PREFIXES = ("frac_", "prev_")


def macro_name(alias: str, key: str) -> str:
    """alias + key translated to letters only (LaTeX macro names cannot
    contain digits or underscores)."""
    parts = []
    for piece in re.findall(r"[A-Za-z]+|[0-9]+", key):
        if piece.isdigit():
            parts.append("".join(DIGITS[int(d)] for d in piece))
        else:
            parts.append(piece[0].upper() + piece[1:])
    return alias + "".join(parts)


def format_number(value) -> str | None:
    """LaTeX text of a number; None for values that cannot be printed."""
    if isinstance(value, bool) or value is None:
        return None
    if isinstance(value, int):
        text = f"{abs(value):,}".replace(",", "{,}")
    elif isinstance(value, float):
        if math.isnan(value) or math.isinf(value):
            return None
        text = f"{abs(value):.3f}"
    else:
        return None
    # A negative value that rounds to zero is printed as 0.000, not -0.000.
    negative = value < 0 and text.strip("0.{,}") != ""
    return ("\\ensuremath{-}" + text) if negative else text


def format_pct(value: float) -> str:
    return f"{100 * value:.1f}\\%"


def build(runs: dict, logs_dir: Path = config.LOGS_DIR,
          allow_fast: bool = False) -> tuple[list[str], list[str]]:
    """Return (lines of numbers.tex, warnings)."""
    lines, warnings, seen = [], [], {}
    sources = []
    for alias, log_name in runs.items():
        if not re.fullmatch(r"[A-Za-z]+", alias):
            raise ValueError(f"alias {alias!r}: letters only")
        path = logs_dir / f"{log_name}.json"
        with open(path, encoding="utf-8") as f:
            log = json.load(f)
        if log.get("fast") and not allow_fast:
            raise ValueError(f"{log_name} is a --fast run; it cannot go "
                             "into the reports (D14)")
        meta = log.get("meta", {})
        shown = (path.relative_to(config.ROOT) if path.is_relative_to(config.ROOT)
                 else path).as_posix()
        sources.append(f"%   {alias}: {shown}"
                       f" (created {meta.get('created')}, git "
                       f"{meta.get('git_commit')}"
                       f"{', uncommitted changes' if meta.get('git_dirty') else ''})")
        lines.append(f"\n% ---- {alias}: {log_name}")
        for key, value in log["scalars"].items():
            text = format_number(value)
            if text is None:
                warnings.append(f"{alias}.{key} = {value!r} not printable;"
                                " macro set to ??")
                text = "\\textbf{??}"
            entries = [(macro_name(alias, key), text)]
            if key.startswith(PCT_PREFIXES) and isinstance(value, float) \
                    and not math.isnan(value):
                entries.append((macro_name(alias, key) + "Pct",
                                format_pct(value)))
            for name, body in entries:
                if name in seen:
                    raise ValueError(f"macro \\{name} produced by both "
                                     f"{seen[name]} and {alias}.{key}")
                seen[name] = f"{alias}.{key}"
                lines.append(f"% {alias}: {key}")
                lines.append(f"\\newcommand{{\\{name}}}{{{body}}}")
    header = [
        "% numbers.tex: generated by report/make_numbers.py on "
        f"{datetime.now():%Y-%m-%d %H:%M}. Do not edit by hand.",
        "% Sources:", *sources]
    return header + lines, warnings


def main(argv=None) -> None:
    p = argparse.ArgumentParser(description="Write report/numbers.tex")
    p.add_argument("--allow-fast", action="store_true",
                   help="accept --fast runs (only to test this script)")
    a = p.parse_args(argv)
    with open(RUNS_FILE, encoding="utf-8") as f:
        runs = json.load(f)
    lines, warnings = build(runs, allow_fast=a.allow_fast)
    OUT_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    n = sum(line.startswith("\\newcommand") for line in lines)
    print(f"{n} macros from {len(runs)} logs written to "
          f"{OUT_FILE.relative_to(config.ROOT).as_posix()}")
    for w in warnings:
        print("WARNING:", w)


if __name__ == "__main__":
    main()
